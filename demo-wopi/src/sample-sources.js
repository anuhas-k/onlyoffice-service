// Hand-built sample files, one per format that is small enough to write by hand. Each is the smallest honest example
// of its format (a few paragraphs / rows / one slide) so the editor has something to open and change.
// Everything else the Document Server can produce is converted from docx / xlsx / odp (samples.js).
import { makeDocx, zip } from './make-docx.js';

const SPREADSHEET = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main';
const REL_NS = 'http://schemas.openxmlformats.org/package/2006/relationships';
const OFFICE_REL = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships';
const XML_DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>';

const TEXT_LINES = ['Sample document', 'This file was generated by the demo so every format can be tested.', 'Edit it, close it, then open History to see the versions.'];

function docx() {
  return makeDocx(TEXT_LINES, { compress: true });
}

const cell = (ref, text) => `<c r="${ref}" t="inlineStr"><is><t>${text}</t></is></c>`;
const num = (ref, value) => `<c r="${ref}"><v>${value}</v></c>`;

function xlsx() {
  const rows = [
    `<row r="1">${cell('A1', 'Item')}${cell('B1', 'Qty')}${cell('C1', 'Price')}</row>`,
    `<row r="2">${cell('A2', 'Apples')}${num('B2', 3)}${num('C2', 1.2)}</row>`,
    `<row r="3">${cell('A3', 'Pears')}${num('B3', 5)}${num('C3', 0.9)}</row>`,
  ].join('');
  return zip({
    '[Content_Types].xml': `${XML_DECL}<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>`,
    '_rels/.rels': `${XML_DECL}<Relationships xmlns="${REL_NS}"><Relationship Id="rId1" Type="${OFFICE_REL}/officeDocument" Target="xl/workbook.xml"/></Relationships>`,
    'xl/workbook.xml': `${XML_DECL}<workbook xmlns="${SPREADSHEET}" xmlns:r="${OFFICE_REL}"><sheets><sheet name="Sheet1" sheetId="1" r:id="rId1"/></sheets></workbook>`,
    'xl/_rels/workbook.xml.rels': `${XML_DECL}<Relationships xmlns="${REL_NS}"><Relationship Id="rId1" Type="${OFFICE_REL}/worksheet" Target="worksheets/sheet1.xml"/></Relationships>`,
    'xl/worksheets/sheet1.xml': `${XML_DECL}<worksheet xmlns="${SPREADSHEET}"><sheetData>${rows}</sheetData></worksheet>`,
  }, false); // stored: the file is a few hundred bytes and stays inspectable
}

const ODF_NS = 'xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0" xmlns:draw="urn:oasis:names:tc:opendocument:xmlns:drawing:1.0" xmlns:presentation="urn:oasis:names:tc:opendocument:xmlns:presentation:1.0" xmlns:svg="urn:oasis:names:tc:opendocument:xmlns:svg-compatible:1.0" xmlns:fo="urn:oasis:names:tc:opendocument:xmlns:xsl-fo-compatible:1.0" xmlns:style="urn:oasis:names:tc:opendocument:xmlns:style:1.0"';
const slide = (n, title) => `<draw:page draw:name="Slide ${n}"><draw:frame presentation:class="title" svg:x="2cm" svg:y="2cm" svg:width="20cm" svg:height="3cm"><draw:text-box><text:p>${title}</text:p></draw:text-box></draw:frame></draw:page>`;
const odpBody = `<office:body><office:presentation>${slide(1, 'Sample presentation')}${slide(2, 'Edit me, then check History')}</office:presentation></office:body>`;

function odp() {
  const mime = 'application/vnd.oasis.opendocument.presentation';
  return zip({
    mimetype: mime, // must be first and stored (the zip is written uncompressed)
    'META-INF/manifest.xml': `${XML_DECL}<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2"><manifest:file-entry manifest:full-path="/" manifest:version="1.2" manifest:media-type="${mime}"/><manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/></manifest:manifest>`,
    'content.xml': `${XML_DECL}<office:document-content ${ODF_NS} office:version="1.2">${odpBody}</office:document-content>`,
  }, false);
}

function pdf() {
  const content = 'BT /F1 24 Tf 72 700 Td (Sample PDF) Tj 0 -32 Td /F1 14 Tf (Generated by the demo so every format can be tested.) Tj ET';
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let out = '%PDF-1.4\n';
  const offsets = objects.map((body, i) => {
    const at = out.length;
    out += `${i + 1} 0 obj\n${body}\nendobj\n`;
    return at;
  });
  const xrefAt = out.length;
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  out += offsets.map((at) => `${String(at).padStart(10, '0')} 00000 n \n`).join('');
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefAt}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

const text = (s) => () => Buffer.from(s, 'utf8');
const html = `<!doctype html>\n<html><head><meta charset="utf-8"><title>Sample</title></head><body><h1>${TEXT_LINES[0]}</h1><p>${TEXT_LINES[1]}</p><p>${TEXT_LINES[2]}</p></body></html>\n`;
const flat = (mime, body) => `${XML_DECL}\n<office:document ${ODF_NS} office:version="1.2" office:mimetype="${mime}">${body}</office:document>\n`;

